#!/usr/bin/env node
// Static generator for learn.yotsubashader.com. No dependencies: Node >= 18.
//   node build.mjs            build into ./dist
//   node build.mjs --serve    build, serve on http://localhost:4174 and rebuild on change
//   SITE_URL=https://learn.yotsubashader.com node build.mjs

import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath } from 'node:url';

import { parseFrontmatter, renderMarkdown } from './lib/markdown.mjs';
import { homePage, chapterPage, notFoundPage, rootRedirect } from './lib/layout.mjs';
import { SITE, LANGS, SECTIONS, ENGINES, UI } from './site.config.mjs';
import { hashBlocks } from './lib/tts.mjs';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.join(ROOT, 'dist');
const CONTENT = path.join(ROOT, 'content');
const STATIC = path.join(ROOT, 'static');
const VIDEOS = path.join(ROOT, 'videos'); // <lang>/<id>.mp4 + .vtt + .jpg + .json, made by promo-video/automation/publish-video.mjs
const AUDIO = path.join(ROOT, 'audio'); // generated by tts.mjs: <lang>/<section>/<page>.json + .mp3
const TTS_DUMP = path.join(ROOT, '.tts'); // spoken text of every page, read by tts.mjs
const args = new Set(process.argv.slice(2));

const urlOf = (lang, section, slug) => `/${lang}/${section}/${slug && slug !== 'index' ? slug + '/' : ''}`;

function write(rel, data) {
  const f = path.join(DIST, rel);
  fs.mkdirSync(path.dirname(f), { recursive: true });
  fs.writeFileSync(f, data);
}
/** Video of a chapter (frontmatter `video: ep01`): only the files of the page's own language are used. */
function videoInfo(lang, id) {
  if (!id) return null;
  const base = path.join(VIDEOS, lang, id);
  if (!fs.existsSync(base + '.mp4')) { console.warn(`Video "${id}" has no ${lang} file (videos/${lang}/${id}.mp4), the page is built without it.`); return null; }
  const meta = fs.existsSync(base + '.json') ? JSON.parse(fs.readFileSync(base + '.json', 'utf8')) : {};
  const has = (ext) => fs.existsSync(base + ext);
  const u = `/videos/${lang}/${id}`;
  return { src: u + '.mp4', vtt: has('.vtt') ? u + '.vtt' : '', poster: has('.jpg') ? u + '.jpg' : '', minutes: meta.minutes || 0, title: meta.title || '' };
}

function copyDir(from, to) {
  if (!fs.existsSync(from)) return;
  fs.cpSync(from, to, { recursive: true });
}

function build() {
  const t0 = Date.now();
  const errors = [];
  fs.rmSync(DIST, { recursive: true, force: true });

  /* pass 1: read content */
  const data = {}; // lang -> section -> [page]
  for (const lang of Object.keys(LANGS)) {
    data[lang] = {};
    for (const s of SECTIONS) {
      const dir = path.join(CONTENT, lang, s.id);
      const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')) : [];
      if (!files.includes('index.md')) errors.push(`content/${lang}/${s.id}/index.md is missing (it is the section overview)`);
      const pages = files.map((f) => {
        const raw = fs.readFileSync(path.join(dir, f), 'utf8');
        const { meta, body } = parseFrontmatter(raw);
        const slug = f.replace(/\.md$/, '');
        if (!meta.title) errors.push(`content/${lang}/${s.id}/${f}: frontmatter "title" is required`);
        return {
          id: slug, slug, file: `${s.id}/${f}`, rel: `${s.id}/${f}`,
          title: meta.title || slug, summary: meta.summary || '', status: meta.status === 'planned' ? 'planned' : 'current',
          order: typeof meta.order === 'number' ? meta.order : slug === 'index' ? -1 : 1000, body,
          video: videoInfo(lang, meta.video),
          url: urlOf(lang, s.id, slug), path: `${s.id}${slug === 'index' ? '' : '/' + slug}`,
        };
      });
      pages.sort((a, b) => a.order - b.order || a.slug.localeCompare(b.slug));
      pages.forEach((p, n) => (p.num = n + 1));
      data[lang][s.id] = pages;
    }
  }
  const byRel = (lang) => new Map(Object.values(data[lang]).flat().map((p) => [p.rel, p]));

  /* pass 2: render */
  const searchIndex = {};
  const allUrls = new Set(['/']);
  const outputs = [];
  const staleAudio = [];
  for (const lang of Object.keys(LANGS)) {
    const rels = byRel(lang);
    searchIndex[lang] = [];
    const sectionInfo = {};
    for (const s of SECTIONS) {
      const pages = data[lang][s.id];
      for (const page of pages) {
        const dir = path.posix.dirname(page.rel);
        const ctx = {
          t: { ...UI[lang] },
          resolveLink(href) {
            if (/^(\/|#|mailto:)/.test(href)) return href;
            const [file, hash] = href.split('#');
            if (!file) return '#' + hash;
            const target = path.posix.normalize(path.posix.join(dir, file));
            const p = rels.get(target);
            if (!p) { errors.push(`${lang}/${page.rel}: broken link "${href}"`); return '#'; }
            return p.url + (hash ? '#' + hash : '');
          },
          resolveAsset(src) {
            if (/^(\/|https?:)/.test(src)) return src;
            const clean = src.replace(/^(\.\.?\/)+/, '');
            if (!fs.existsSync(path.join(CONTENT, clean))) errors.push(`${lang}/${page.rel}: missing image "${src}"`);
            return '/' + clean;
          },
        };
        const r = renderMarkdown(page.body, ctx);
        Object.assign(page, { html: r.html, headings: r.headings, usesStyles: r.usesStyles, text: r.text });
        page.minutes = Math.max(1, Math.round(r.text.split(/\s+/).length / 200));
        searchIndex[lang].push({
          u: page.url, t: page.title, s: UI[lang].sections[s.id].short,
          h: r.headings.map((h) => [h.id, h.text]), x: (page.summary + ' ' + r.text).slice(0, 4000),
        });
      }
      sectionInfo[s.id] = { count: pages.length, minutes: pages.reduce((a, p) => a + p.minutes, 0) };
    }

    const altFor = (page) =>
      Object.fromEntries(Object.keys(LANGS).map((l) => [l, byRel(l).has(page.rel) ? byRel(l).get(page.rel).url : `/${l}/`]));
    const home = homePage({ lang, sections: sectionInfo, alt: Object.fromEntries(Object.keys(LANGS).map((l) => [l, `/${l}/`])) });
    outputs.push([`${lang}/index.html`, home]);
    allUrls.add(`/${lang}/`);
    for (const s of SECTIONS) {
      const pages = data[lang][s.id];
      pages.forEach((page, index) => {
        allUrls.add(page.url);
        const key = page.url.slice(1, -1); // es/get-started/colors
        const speech = {
          // Called with the page's spoken blocks. Returns the timing file URL only when audio exists AND was made from this exact text.
          audioFor(blocks) {
            const hash = hashBlocks(blocks);
            fs.mkdirSync(path.dirname(path.join(TTS_DUMP, key)), { recursive: true });
            fs.writeFileSync(path.join(TTS_DUMP, key + '.json'), JSON.stringify({ key, lang, hash, blocks }));
            const f = path.join(AUDIO, key + '.json');
            if (!fs.existsSync(f)) return null;
            if (JSON.parse(fs.readFileSync(f, 'utf8')).hash !== hash) { staleAudio.push(key); return null; }
            return `/audio/${key}.json`;
          },
        };
        outputs.push([page.url.slice(1) + 'index.html', chapterPage({ lang, section: s.id, pages, page, index, alt: altFor(page), speech })]);
      });
    }
    outputs.push([`${lang}/404.html`, notFoundPage(lang)]);
  }
  for (const [f, html] of outputs) write(f, html);
  write('index.html', rootRedirect());
  write('404.html', notFoundPage(SITE.defaultLang));
  for (const lang of Object.keys(LANGS)) write(`search-${lang}.json`, JSON.stringify(searchIndex[lang]));
  write('robots.txt', `User-agent: *\nAllow: /\nSitemap: ${SITE.url}/sitemap.xml\n`);
  write(
    'sitemap.xml',
    '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' +
      [...allUrls].filter((u) => u !== '/').map((u) => `<url><loc>${SITE.url}${u}</loc></url>`).join('') + '</urlset>',
  );
  copyDir(STATIC, DIST);
  copyDir(path.join(CONTENT, 'assets'), path.join(DIST, 'assets'));
  copyDir(AUDIO, path.join(DIST, 'audio'));
  copyDir(VIDEOS, path.join(DIST, 'videos'));
  if (staleAudio.length) console.warn(`Audio out of date (text changed, run node tts.mjs): ${staleAudio.join(', ')}`);

  /* engine pages must exist for every logo in the home row */
  for (const e of ENGINES) {
    for (const lang of Object.keys(LANGS)) {
      if (!allUrls.has(urlOf(lang, 'engines', e.id))) errors.push(`engine "${e.id}" has no page: content/${lang}/engines/${e.id}.md`);
    }
  }

  /* internal link check on the generated HTML */
  for (const [f, html] of outputs) {
    for (const m of html.matchAll(/href="(\/[^"#?]*)(?:\?[^"#]*)?(?:#[^"]*)?"/g)) {
      const u = m[1];
      if (/\.[a-z0-9]+$/i.test(u) || allUrls.has(u)) continue;
      errors.push(`${f}: link to missing page ${u}`);
    }
  }

  const pageCount = outputs.length;
  if (errors.length) {
    console.error(`\nBuild found ${errors.length} problem(s):\n - ${[...new Set(errors)].join('\n - ')}\n`);
    if (!args.has('--serve')) process.exit(1);
  }
  console.log(`Built ${pageCount} pages in ${Date.now() - t0} ms -> ${path.relative(process.cwd(), DIST) || 'dist'}`);
}

if (args.has('--serve')) {
  const run = () => { try { build(); } catch (e) { console.error(e); } };
  run();
  let timer;
  for (const d of [CONTENT, STATIC, path.join(ROOT, 'lib'), path.join(ROOT, 'site.config.mjs'), VIDEOS]) {
    if (fs.existsSync(d)) fs.watch(d, { recursive: true }, () => { clearTimeout(timer); timer = setTimeout(run, 150); });
  }
  const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.webp': 'image/webp', '.xml': 'application/xml', '.txt': 'text/plain', '.mp3': 'audio/mpeg', '.mp4': 'video/mp4', '.vtt': 'text/vtt; charset=utf-8', '.jpg': 'image/jpeg' };
  http
    .createServer((req, res) => {
      let p = decodeURIComponent(req.url.split('?')[0]);
      let f = path.join(DIST, p);
      if (!f.startsWith(DIST)) { res.writeHead(403).end(); return; }
      if (fs.existsSync(f) && fs.statSync(f).isDirectory()) f = path.join(f, 'index.html');
      if (!fs.existsSync(f)) {
        res.writeHead(404, { 'content-type': types['.html'] }).end(fs.readFileSync(path.join(DIST, '404.html')));
        return;
      }
      const data = fs.readFileSync(f);
      const headers = { 'content-type': types[path.extname(f)] || 'application/octet-stream', 'cache-control': 'no-store', 'accept-ranges': 'bytes' };
      const range = /^bytes=(\d*)-(\d*)$/.exec(req.headers.range || ''); // audio players seek with Range requests
      if (range) {
        const start = range[1] ? +range[1] : 0;
        const end = Math.min(range[2] ? +range[2] : data.length - 1, data.length - 1);
        res.writeHead(206, { ...headers, 'content-range': `bytes ${start}-${end}/${data.length}`, 'content-length': end - start + 1 }).end(data.subarray(start, end + 1));
      } else res.writeHead(200, headers).end(data);
    })
    .listen(4174, () => console.log('Serving http://localhost:4174'));
} else build();
