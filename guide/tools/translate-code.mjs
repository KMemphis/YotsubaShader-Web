const missing = new Set();
const tr = (text) => {
  const key = text.trim();
  if (!key) return text;
  if (T[key] != null) return text.replace(key, T[key]);
  missing.add(key);
  return text;
};

fs.mkdirSync(DST, { recursive: true });
for (const f of fs.readdirSync(SRC)) {
  let s = fs.readFileSync(SRC + f, 'utf8');
  if (/\.(cs)$/.test(f)) {
    s = s.replace(/\/\*([\s\S]*?)\*\//g, (m, body) => `/*${tr(body)}*/`);
    s = s.replace(/(^|[^:"'])\/\/ ?([^\n]*)/g, (m, pre, body) => `${pre}// ${tr(body)}`);
    s = s.replace(/\$?"[^"\n]*[A-Za-z]{3,} [^"\n]*"/g, (m) => {
      const inner = m.replace(/^\$?"|"$/g, '');
      return T[inner] != null ? m.replace(inner, T[inner]) : m;
    });
  } else if (/\.xml$/.test(f)) {
    s = s.replace(/<!--([\s\S]*?)-->/g, (m, body) => `<!-- ${tr(body)} -->`);
  } else if (/\.yml$/.test(f)) {
    s = s.replace(/^(\s*)# (.*)$/gm, (m, ind, body) => `${ind}# ${tr(body)}`);
  }
  fs.writeFileSync(DST + f, s);
}
if (missing.size) {
  console.error('Comments without a Spanish translation:\n  ' + [...missing].join('\n  '));
  process.exit(1);
}
