import React from 'react';
import { Appear, C, Headline, Kicker, SceneFrame } from '../../ep01/kit';
import { cue, ramp, scene, useT, T } from '../../ep01/data';
import { Box, Mono } from '../common';
import { CodeCard } from '../CodeCard';

const ID = 'v2-s05b-languages';

const CS_GLSL = ['public struct Corner', '{', '    [location(0)] public vec2 Position;', '    [location(1)] public vec4 Color;', '}'];
const CS_HLSL = ['public struct Corner', '{', '    [TEXCOORD(0)] public vec2 Position;', '    [TEXCOORD(1)] public vec4 Color;', '}'];
const CS_MIX = ['public struct Corner', '{', '    [POSITION] public vec2 Position;', '    [location(1)] public vec4 Color;', '}'];
// verbatim excerpts of what the real compiler generated for these shaders
const OUT_GLSL = ['layout(location = 0) in vec2 corner_Position;', 'layout(location = 1) in vec4 corner_Color;'];
const OUT_HLSL = ['struct SPIRV_Cross_Input', '{', '    float2 corner_Position : TEXCOORD0;', '    float4 corner_Color : TEXCOORD1;', '};'];

export const S05b: React.FC = () => {
  const t = useT();
  const s = scene(ID);
  const cLoc = cue(ID, 'is called location');
  const cHlsl = cue(ID, 'HLSL, the language of DirectX');
  const cWhich = cue(ID, 'which one do you use');
  const cBoth = cue(ID, 'understands the attributes of both');
  const cGlsl = cue(ID, 'written the GLSL way');
  const cHway = cue(ID, 'written the HLSL way');
  const cSame = cue(ID, 'say the same thing');
  const cConcept = cue(ID, 'the concept behind each word');
  const cDiff = cue(ID, 'There is one difference');
  const cLoc2 = cue(ID, 'With location, you choose the number');
  const cSem = cue(ID, 'With a semantic like');
  const cMix = cue(ID, 'You can also mix them');
  const cPos = cue(ID, 'uses the HLSL word');
  const cLoc1 = cue(ID, 'location one');
  const cFree = cue(ID, 'the free number');
  const cWhich2 = cue(ID, 'Whichever style you choose');
  const cComp = cue(ID, 'We compiled these three versions');
  const cIdent = cue(ID, 'came out identical');
  const cNames = cue(ID, 'only keep the names');
  const cFrom = cue(ID, 'From here on');
  const cAll = cue(ID, 'Everything we see');
  const k = (a: number, b = a + 0.5) => ramp(t, a, b);
  const vis = (a: number, b: number) => Math.min(k(a, a + 0.5), 1 - ramp(t, b - 0.4, b));
  const v1 = vis(s.start, cGlsl - 0.1), v2 = vis(cGlsl - 0.1, cDiff - 0.1), v3 = vis(cDiff - 0.1, cMix - 0.1), v4 = vis(cMix - 0.1, cWhich2 - 0.1), v5 = vis(cWhich2 - 0.1, cFrom - 0.1), v6 = k(cFrom - 0.1, cFrom + 0.4);
  const Layer: React.FC<{ o: number; children: React.ReactNode }> = ({ o, children }) => (o > 0.01 ? <div style={{ position: 'absolute', inset: 0, opacity: o }}>{children}</div> : null);
  const tiles = [
    { n: 'GLSL', at: cIdent, same: true }, { n: 'GLSL ES', at: cIdent + 0.35, same: true }, { n: 'Metal', at: cIdent + 0.7, same: true },
    { n: 'C++', at: cIdent + 1.05, same: true }, { n: 'HLSL', at: cNames, same: false }, { n: 'SPIR-V', at: cNames + 0.4, same: false },
  ];
  return (
    <SceneFrame id={ID}>
      <Appear at={s.start + 0.3} dur={0.7} style={{ position: 'absolute', left: 80, top: 20, opacity: 1 - v6 }}><Kicker>{T('Two ways to write the same thing')}</Kicker></Appear>

      <Layer o={v1}>
        {[{ n: 'GLSL', w: 'location(0)', sub: 'OpenGL · Vulkan', at: cLoc, x: 80, c: C.blue }, { n: 'HLSL', w: 'TEXCOORD0', sub: 'DirectX', at: cHlsl, x: 980, c: C.violet }].map((c) => (
          <Appear key={c.n} at={c.at - 0.2} dur={0.6} rise={16} style={{ position: 'absolute', left: c.x, top: 130, width: 860 }}>
            <Box style={{ padding: '36px 44px', borderTop: `6px solid ${c.c}`, height: 300 }}>
              <div style={{ fontSize: 40, fontWeight: 700, color: c.c }}>{c.n}</div>
              <div style={{ marginTop: 30 }}><Mono size={72} color={C.ink}>{c.w}</Mono></div>
              <div style={{ marginTop: 26, fontSize: 32, color: C.dim, fontWeight: 600 }}>{T(c.sub)}</div>
            </Box>
          </Appear>
        ))}
        <Appear at={cWhich} dur={0.6} style={{ position: 'absolute', left: 80, top: 520, width: 1760, fontSize: 52, fontWeight: 700 }}>{T('Which one do you use? The one you already know.')}</Appear>
        <Appear at={cBoth} dur={0.6} style={{ position: 'absolute', left: 80, top: 620, width: 1760, fontSize: 44, fontWeight: 500, color: C.mint }}>{T('Yotsuba Shader understands the attributes of both.')}</Appear>
      </Layer>

      <Layer o={v2}>
        <Appear at={cGlsl} dur={0.6} style={{ position: 'absolute', left: 80, top: 90 }}><Kicker color={C.blue}>{T('GLSL style')}</Kicker></Appear>
        <CodeCard title="C# · GLSL STYLE" lines={CS_GLSL} x={80} y={140} w={820} opacity={k(cGlsl)} />
        <CodeCard title={T('GLSL · generated by the compiler').toUpperCase()} lines={OUT_GLSL} x={80} y={440} w={820} opacity={k(cGlsl + 1.2)} fs={22} />
        <Appear at={cHway} dur={0.6} style={{ position: 'absolute', left: 1020, top: 90 }}><Kicker color={C.violet}>{T('HLSL style')}</Kicker></Appear>
        <CodeCard title="C# · HLSL STYLE" lines={CS_HLSL} x={1020} y={140} w={820} opacity={k(cHway)} />
        <CodeCard title={T('HLSL · generated by the compiler').toUpperCase()} lines={OUT_HLSL} x={1020} y={440} w={820} opacity={k(cHway + 1.2)} fs={22} />
        <Appear at={cSame} dur={0.5} style={{ position: 'absolute', left: 900, top: 230, width: 120, textAlign: 'center', fontSize: 90, fontWeight: 700, color: C.mint }}>=</Appear>
        <Appear at={cConcept} dur={0.7} style={{ position: 'absolute', left: 80, top: 720, width: 1760, fontSize: 38, fontWeight: 600 }}>{T('Each language has its own words. Yotsuba Shader knows the concept behind each one.')}</Appear>
      </Layer>

      <Layer o={v3}>
        <Appear at={cLoc2 - 0.2} dur={0.6} rise={16} style={{ position: 'absolute', left: 80, top: 130, width: 820 }}>
          <Box style={{ padding: '36px 44px', borderTop: `6px solid ${C.blue}`, height: 400 }}>
            <Mono size={56} color={C.blue}>location(1)</Mono>
            <div style={{ marginTop: 28, fontSize: 48, fontWeight: 700 }}>{T('You choose the number.')}</div>
          </Box>
        </Appear>
        <Appear at={cSem - 0.2} dur={0.6} rise={16} style={{ position: 'absolute', left: 1020, top: 130, width: 820 }}>
          <Box style={{ padding: '36px 44px', borderTop: `6px solid ${C.violet}`, height: 400 }}>
            <Mono size={56} color={C.violet}>TEXCOORD(0)</Mono>
            <div style={{ marginTop: 28, fontSize: 48, fontWeight: 700, lineHeight: 1.2 }}>{T('The compiler chooses the number.')}</div>
            <div style={{ marginTop: 18, fontSize: 32, color: C.dim, fontWeight: 500 }}>{T('It connects the two stages by name.')}</div>
          </Box>
        </Appear>
      </Layer>

      <Layer o={v4}>
        <CodeCard title="C# · MIXED" lines={CS_MIX} x={80} y={130} w={820} opacity={k(cMix)}
          bands={[{ line: 2, color: C.pink, o: Math.min(k(cPos), 1 - k(cLoc1 - 0.1)) + 0 }, { line: 3, color: C.mint, o: k(cLoc1) }]} />
        <CodeCard title={T('GLSL · generated by the compiler').toUpperCase()} lines={OUT_GLSL} x={1020} y={130} w={820} fs={22} opacity={k(cFree - 0.3)}
          bands={[{ line: 0, color: C.pink, o: k(cFree) }, { line: 1, color: C.mint, o: k(cFree) }]} />
        <Appear at={cFree} dur={0.6} style={{ position: 'absolute', left: 80, top: 420, width: 1760, fontSize: 48, fontWeight: 700 }}>
          <Mono size={48} color={C.pink}>POSITION</Mono> → {T('the free number')}: <Mono size={48} color={C.pink}>0</Mono>
        </Appear>
      </Layer>

      <Layer o={v5}>
        {['GLSL style', 'HLSL style', 'Mixed'].map((n, i) => (
          <Appear key={n} at={cWhich2 + 0.3 + i * 0.6} dur={0.5} rise={12} style={{ position: 'absolute', left: 80, top: 150 + i * 150, width: 440 }}>
            <Box style={{ padding: '30px 32px', borderLeft: `6px solid ${[C.blue, C.violet, C.pink][i]}`, fontSize: 36, fontWeight: 600 }}>{T(n)}</Box>
          </Appear>
        ))}
        <Appear at={cWhich2 + 2.2} dur={0.5} style={{ position: 'absolute', left: 540, top: 270, width: 140, textAlign: 'center', fontSize: 64, color: C.dim }}>→</Appear>
        {tiles.map((tl, i) => (
          <Appear key={tl.n} at={cWhich2 + 2.8 + i * 0.5} dur={0.5} rise={12} style={{ position: 'absolute', left: 700 + (i % 3) * 380, top: 150 + Math.floor(i / 3) * 210, width: 350 }}>
            <Box style={{ padding: '26px 28px', borderTop: `5px solid ${ramp(t, tl.at, tl.at + 0.4) > 0.5 ? (tl.same ? C.green : C.amber) : C.line}`, height: 150 }}>
              <div style={{ fontSize: 40, fontWeight: 700 }}>{tl.n}</div>
              <div style={{ marginTop: 14, fontSize: 28, fontWeight: 600, opacity: ramp(t, tl.at, tl.at + 0.4), color: tl.same ? C.green : C.amber }}>{tl.same ? T('identical') : T('names kept')}</div>
            </Box>
          </Appear>
        ))}
        <Appear at={cNames + 1} dur={0.6} style={{ position: 'absolute', left: 80, top: 640, width: 1760, fontSize: 34, color: C.dim, fontWeight: 500 }}>{T('Compiled with the real compiler. The three versions give the same GLSL, GLSL ES, Metal and C++, character by character.')}</Appear>
      </Layer>

      <Layer o={v6}>
        <div style={{ position: 'absolute', left: 80, top: 250, width: 1760 }}>
          <Kicker color={C.pink}>{T('From here on')}</Kicker>
          <Headline size={96} style={{ marginTop: 20 }}>{T('We keep building with HLSL attributes')}</Headline>
          <Appear at={cAll} dur={0.7} style={{ marginTop: 40, fontSize: 44, fontWeight: 500, color: C.dim }}>{T('Everything also works with location.')}</Appear>
        </div>
      </Layer>
    </SceneFrame>
  );
};
